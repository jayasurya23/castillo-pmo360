def _purge_prior_test_data(session) -> None:
    """Remove any pre-existing test client + project so the run is fresh."""
    existing_project = (
        session.query(Project).filter_by(name=TEST_PROJECT_NAME).first()
    )
    if existing_project:
        session.delete(existing_project)
    existing_client = (
        session.query(Client).filter_by(name=TEST_CLIENT_NAME).first()
    )
    if existing_client:
        session.delete(existing_client)
    session.flush()


