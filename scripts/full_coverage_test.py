def main() -> None:
    init_db()
    session = get_session_factory()()
    try:
        _purge_prior_test_data(session)

        client, project, meeting = _build_test_meeting(session)
        # Commit so the meeting + schedule + actions are visible to the agenda
        # generator path (it re-opens its own session in places).
        session.commit()

        proj_slug = safe_filename_slug(project.name)

        # ---- Meeting Minutes PDF ----
        print(f"Building meeting minutes for {meeting.title}…")
        mm_pdf = generate_meeting_minutes_pdf(meeting)
        mm_path = (
            OUTPUT_DIR
            / f"TEST_{proj_slug}_Meeting_Minutes_{meeting.meeting_date.isoformat()}.pdf"
        )
        mm_path.write_bytes(mm_pdf)
        print(f"  OK -> {mm_path}  ({len(mm_pdf):,} bytes)")

        # ---- Pre-Meeting Agenda PDF ----
        print()
        print("Building pre-meeting agenda…")
        payload = _build_full_agenda_payload(meeting)
        upcoming = payload.pop("upcoming")

        draft = generate_next_agenda(
            session, project, upcoming,
            source_meeting_id=meeting.id,
        )

        from db.repository import open_actions, deliverables_to_carry_forward
        carry_actions = list(open_actions(session, project.id))
        carry_deliv = list(
            deliverables_to_carry_forward(session, project.id)
        )

        agenda_pdf = generate_premeeting_agenda_pdf(
            meeting=draft,
            prior_meeting=meeting,
            carry_actions=carry_actions,
            carry_deliverables=carry_deliv,
            schedule=session.query(Schedule)
                .filter_by(project_id=project.id).first(),
            **payload,
        )
        ag_path = (
            OUTPUT_DIR
            / f"TEST_{proj_slug}_Pre_Meeting_Agenda_{upcoming.isoformat()}.pdf"
        )
        ag_path.write_bytes(agenda_pdf)
        print(f"  OK -> {ag_path}  ({len(agenda_pdf):,} bytes)")

        # ---- Persist as a saved Agenda so it shows up in History ----
        print()
        print("Saving agenda to DB so it appears under History > Pre-Meeting Agendas...")

        # Serialize the in-memory trees + dicts into the JSON shapes the
        # editor expects. Decision dates → ISO strings. DP trees → textarea text.
        dp_text_payload = {
            disc: _dps_to_text(tree)
            for disc, tree in payload["dp_by_discipline"].items()
        }
        # Disciplines that the UI added but had no content still get an empty entry
        for disc in payload["disciplines"]:
            dp_text_payload.setdefault(disc, "")
        recap_text_payload = {
            disc: _dps_to_text(tree)
            for disc, tree in payload["recap_by_discipline"].items()
        }
        for disc in payload["disciplines"]:
            recap_text_payload.setdefault(disc, "")

        attendees_payload = [
            {
                "full_name": a.full_name,
                "initials":  a.initials,
                "organization": a.organization,
            }
            for a in meeting.attendees
        ]
        open_actions_payload = [
            {
                "text":     a.text,
                "owner":    a.owner or "",
                "due_date": a.due_date.isoformat() if a.due_date else None,
                "status":   (a.status or "open").capitalize(),
            }
            for a in carry_actions
        ]
        decisions_payload = []
        for d in payload["decisions"]:
            d2 = dict(d)
            rb = d2.get("required_by")
            if rb and not isinstance(rb, str):
                d2["required_by"] = rb.isoformat()
            decisions_payload.append(d2)

        saved = save_agenda(
            session=session,
            project_id=project.id,
            upcoming_date=upcoming,
            source_meeting_id=meeting.id,
            title="Full coverage sample agenda",
            disciplines=payload["disciplines"],
            dp_text=dp_text_payload,
            recap_text=recap_text_payload,
            attendees=attendees_payload,
            open_actions=open_actions_payload,
            risks=payload["risks"],
            decisions=decisions_payload,
        )
        session.commit()
        print(f"  OK -> Saved Agenda id={saved.id} on project {project.name!r}")
        print(
            "        Open the app -> History -> Pre-Meeting Agendas to "
            "see it; click Open to load into Next Agenda for testing."
        )

        # Section coverage summary
        print()
        print("Coverage summary:")
        print(f"  Meeting attendees ............ {len(meeting.attendees)}")
        print(f"  Meeting agenda items ......... {len(meeting.agenda_items)}")
        print(f"  Discussion points + sub ...... "
              f"{sum(1 + len(dp.sub_points) for dp in meeting.discussion_points if dp.parent_id is None)}")
        print(f"  Action items raised .......... {len(meeting.raised_actions)}")
        print(f"  Deliverables on meeting ...... {len(meeting.meeting_deliverables)}")
        print()
        print(f"  Agenda disciplines ........... {len(payload['disciplines'])}")
        print(f"  Agenda DP points ............. "
              f"{sum(len(v) for v in payload['dp_by_discipline'].values())}")
        print(f"  Agenda recap items ........... "
              f"{sum(len(v) for v in payload['recap_by_discipline'].values())}")
        print(f"  Agenda risks ................. {len(payload['risks'])}")
        print(f"  Agenda decisions ............. {len(payload['decisions'])}")
        print(f"  Agenda schedule changes ...... {len(payload['schedule_changes'])}")
        print(f"  Carry-forward actions ........ {len(carry_actions)}")
        print(f"  Carry-forward deliverables ... {len(carry_deliv)}")
        print()
        print("Done. Open the two PDFs above to review.")
    finally:
        session.close()


if __name__ == "__main__":
    main()
