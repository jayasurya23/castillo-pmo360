def _dps_to_text(dps, level: int = 0) -> str:
    """Serialize a ParsedDiscussionPoint tree into the indented-bullet text
    format the textareas use ("- Label: content", 2-space indent per level).
    Mirrors the helper of the same name in app/main.py — kept inline here so
    this script doesn't need to import the Streamlit module."""
    if not dps:
        return ""
    out = []
    indent = "  " * level
    for dp in dps:
        label = (dp.label or "").strip()
        content = (dp.content or "").strip()
        body = f"{label}: {content}" if label else content
        out.append(f"{indent}- {body}")
        kids = getattr(dp, "sub_points", None) or []
        if kids:
            child = _dps_to_text(kids, level + 1)
            if child:
                out.append(child)
    return "\n".join(filter(None, out))


TEST_CLIENT_NAME = "TestCo Renewables"
